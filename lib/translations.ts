type NestedKeyOf<T> =
  T extends string
    ? never
    : {
        [K in keyof T & string]:
          T[K] extends string
            ? K
            : `${K}.${NestedKeyOf<T[K]>}`
      }[keyof T & string]

export type TranslationKey = NestedKeyOf<(typeof translations)["tr"]>

function getNested(o: unknown, path: string): unknown {
  return path.split(".").reduce((acc: any, part) => (acc ? acc[part] : undefined), o)
}

export function getTranslation(lang: Language, key: TranslationKey): string {
  const fromLang = getNested(translations[lang], key)
  if (typeof fromLang === "string") return fromLang

  const fromTr = getNested(translations.tr, key)
  if (typeof fromTr === "string") return fromTr

  return key // fallback: anahtarın kendisini göster
}
